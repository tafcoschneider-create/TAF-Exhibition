-- 1. Staff profiles
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null default '',
    role text not null default 'staff'
        check (role in ('staff', 'admin')),
    created_at timestamptz not null default now()
);

-- 2. Visitors / Leads
create table if not exists public.leads (
    id bigint generated by default as identity primary key,

    created_by uuid not null references public.profiles(id),

    full_name text not null,
    mobile text,
    email text,
    company text,
    job_title text,
    industry text,

    brand text check (
        brand is null or
        brand in (
            'Schneider Electric',
            'Weidmuller',
            'Both',
            'Other'
        )
    ),

    request_type text,

    priority text not null default 'normal'
        check (priority in ('low', 'normal', 'high', 'urgent')),

    product text,
    notes text,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- 3. Indexes
create index if not exists leads_created_by_idx
on public.leads(created_by);

create index if not exists leads_created_at_idx
on public.leads(created_at desc);

-- 4. Automatically create staff profile after signup
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, full_name, role)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', ''),
        'staff'
    )
    on conflict (id) do nothing;

    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();

-- 5. Admin checking function
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
        and role = 'admin'
    );
$$;

-- 6. Enable Row Level Security
alter table public.profiles enable row level security;
alter table public.leads enable row level security;

-- 7. Profiles policies
drop policy if exists "Read own profile or admin"
on public.profiles;

create policy "Read own profile or admin"
on public.profiles
for select
to authenticated
using (
    id = (select auth.uid())
    or (select public.is_admin())
);

-- 8. Leads: staff see their own, admin sees all
drop policy if exists "Read own leads or admin"
on public.leads;

create policy "Read own leads or admin"
on public.leads
for select
to authenticated
using (
    created_by = (select auth.uid())
    or (select public.is_admin())
);

-- 9. Insert leads
drop policy if exists "Insert own leads"
on public.leads;

create policy "Insert own leads"
on public.leads
for insert
to authenticated
with check (
    created_by = (select auth.uid())
);

-- 10. Update leads
drop policy if exists "Update own leads or admin"
on public.leads;

create policy "Update own leads or admin"
on public.leads
for update
to authenticated
using (
    created_by = (select auth.uid())
    or (select public.is_admin())
)
with check (
    created_by = (select auth.uid())
    or (select public.is_admin())
);

-- 11. Delete leads
drop policy if exists "Delete own leads or admin"
on public.leads;

create policy "Delete own leads or admin"
on public.leads
for delete
to authenticated
using (
    created_by = (select auth.uid())
    or (select public.is_admin())
);

